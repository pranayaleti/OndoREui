/**
 * Registry behind the blog index (app/blog/page-client.tsx).
 *
 * The index used to be a hand-typed copy of post data that drifted: it omitted dozens of
 * posts, was not date-sorted, and showed read times nobody had measured. It now reads this
 * one list. `lib/blog-posts.test.ts` renders every app/blog/<slug>/page.tsx and fails when
 * an entry disagrees with its page (title, description, date, category, read time), when an
 * indexable post is missing here, or when a noindex post is still listed. So adding a post
 * means adding one entry; retiring one (noindex) means deleting its entry.
 *
 * `readMinutes` is the number the post's own byline shows (same word count, same
 * readingTimeMinutes()). Hand-built pages without a byline leave it out rather than guess.
 */
