const nodesById = new Map(NODES.map((node) => [node.id, node]))
const nodesByPath = new Map(NODES.map((node) => [normalizeContentPath(node.path), node]))

export function normalizeContentPath(path: string): string {
  if (!path) return "/"
  const withSlash = path.startsWith("/") ? path : `/${path}`
  if (withSlash.length > 1 && withSlash.endsWith("/")) {
    return withSlash.slice(0, -1)
  }
  return withSlash
}

export function getContentNode(id: string): ContentNode | undefined {
  return nodesById.get(id)
}

export function getContentNodeByPath(path: string): ContentNode | undefined {
  return nodesByPath.get(normalizeContentPath(path))
}

export function getAllContentNodes(): readonly ContentNode[] {
  return NODES
}

export function getCluster(id: TopicClusterId): TopicCluster | undefined {
  return TOPIC_CLUSTERS.find((cluster) => cluster.id === id)
}

export function nodesInCluster(clusterId: TopicClusterId): ContentNode[] {
  return NODES.filter((node) => node.cluster === clusterId)
}

export function relatedNodes(id: string): ContentNode[] {
  const node = nodesById.get(id)
  if (!node) return []
  return node.related
    .map((relatedId) => nodesById.get(relatedId))
    .filter((related): related is ContentNode => Boolean(related))
}

export function relatedLinksForPath(
  path: string,
  options?: { kinds?: readonly ContentNode["kind"][]; limit?: number },
): Array<{ label: string; href: string; description: string }> {
  const node = getContentNodeByPath(path)
  if (!node) return []
  let related = relatedNodes(node.id)
  if (options?.kinds?.length) {
    const kindSet = new Set(options.kinds)
    related = related.filter((item) => kindSet.has(item.kind))
  }
  const limit = options?.limit ?? 6
  return related.slice(0, limit).map((item) => ({
    label: item.title,
    href: item.path,
    description: item.description,
  }))
}

export function ctaForPath(path: string): ContentNode["cta"] | undefined {
  return getContentNodeByPath(path)?.cta
}

export function assertContentGraph(): string[] {
  const errors: string[] = []
  const ids = new Set<string>()
  const paths = new Set<string>()

  for (const node of NODES) {
    if (ids.has(node.id)) errors.push(`Duplicate content id: ${node.id}`)
    ids.add(node.id)
    const path = normalizeContentPath(node.path)
    if (paths.has(path)) errors.push(`Duplicate content path: ${path}`)
    paths.add(path)
    for (const relatedId of node.related) {
      if (!nodesById.has(relatedId)) {
        errors.push(`${node.id} related to missing id ${relatedId}`)
      }
    }
    if (!TOPIC_CLUSTER_IDS.includes(node.cluster)) {
      errors.push(`${node.id} has unknown cluster ${node.cluster}`)
    }
  }

  for (const cluster of TOPIC_CLUSTERS) {
    if (!nodesById.has(cluster.pillarId)) {
      errors.push(`Cluster ${cluster.id} pillar ${cluster.pillarId} is missing`)
    }
  }

  return errors
}
